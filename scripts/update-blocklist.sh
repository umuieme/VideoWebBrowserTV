#!/usr/bin/env bash
#
# Regenerates app/src/main/assets/blocklist/ad-domains.txt from the StevenBlack unified hosts
# list (adware + malware), MIT licensed: https://github.com/StevenBlack/hosts
#
# Usage: scripts/update-blocklist.sh        (run from anywhere; needs curl, awk, sort)
#
# The hosts file has lines like "0.0.0.0 ads.example.com". We keep only the domain, drop the
# few entries that are local names rather than ad domains, lowercase, de-duplicate and sort, so
# re-running the script produces a clean diff.

set -euo pipefail

SOURCE_URL="https://raw.githubusercontent.com/StevenBlack/hosts/master/hosts"
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT_DIR="$REPO_ROOT/app/src/main/assets/blocklist"
OUT_FILE="$OUT_DIR/ad-domains.txt"

WORK_DIR="$(mktemp -d)"
trap 'rm -rf "$WORK_DIR"' EXIT

echo "Downloading $SOURCE_URL"
curl --fail --silent --show-error --location --max-time 120 -o "$WORK_DIR/hosts" "$SOURCE_URL"

# $1 is the sink address, $2 the domain. Only sink lines count; skip local names and anything
# that isn't a plain host name (the regex rejects IPs-as-names, wildcards and odd characters).
awk '
  ($1 == "0.0.0.0" || $1 == "127.0.0.1") && NF >= 2 {
    d = tolower($2)
    if (d == "0.0.0.0" || d == "localhost" || d == "localhost.localdomain" || d == "local" \
        || d == "broadcasthost" || d == "ip6-localhost" || d == "ip6-loopback") next
    if (d !~ /^[a-z0-9_-]+(\.[a-z0-9_-]+)+$/) next
    print d
  }
' "$WORK_DIR/hosts" | LC_ALL=C sort -u > "$WORK_DIR/domains"

COUNT="$(wc -l < "$WORK_DIR/domains" | tr -d ' ')"
if [ "$COUNT" -lt 1000 ]; then
  echo "Only $COUNT domains extracted; refusing to overwrite $OUT_FILE" >&2
  exit 1
fi

mkdir -p "$OUT_DIR"
{
  echo "# Ad and tracking domains blocked by the app (one per line; '#' starts a comment)."
  echo "# Source: StevenBlack unified hosts (adware + malware), $SOURCE_URL"
  echo "# License: MIT, Copyright (c) Steven Black. https://github.com/StevenBlack/hosts/blob/master/license.txt"
  echo "# Generated by scripts/update-blocklist.sh on $(date -u +%Y-%m-%d). Domains: $COUNT"
  cat "$WORK_DIR/domains"
} > "$OUT_FILE"

echo "Wrote $COUNT domains to $OUT_FILE"
